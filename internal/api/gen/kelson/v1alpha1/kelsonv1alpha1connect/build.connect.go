// BuildService: the build plane over the API (issues #48, #49, #54, ADR-0010).
//
// `kelson build` already turns a Project's source into a digest-pinned image
// with an in-cluster Job — BuildKit for a Dockerfile, the Cloud Native
// Buildpacks lifecycle without one (docs/build.md). This service is that same
// pipeline reached over the schema, so a UI or an agent can build without a
// kubeconfig and without the CLI — which is what the browser create-from-git
// path (#63) needs, since a browser has neither.
//
// # What the server decides and what it does not
//
// The split is the CLI's, unchanged (ADR-0010): *how* to build comes from the
// spec, *where* the image goes is infrastructure configuration. The request may
// override the destination because a caller may legitimately push somewhere
// else; it may not override the strategy, because that would put build
// configuration in the caller's hands rather than in the spec's, which is
// exactly what ADR-0010 forbids. There is deliberately no strategy field here.

