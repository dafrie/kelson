// EventService: the watch stream agents and the UI react to (#76).
//
// Every other RPC answers a question that was asked. This one answers the
// question nobody wants to keep asking: "did anything change?". Without it an
// agent polls Status in a loop and a UI card is stale until someone reloads.
//
// # What an event is
//
// The taxonomy is deliberately the one that exists today. A STATUS_TRANSITION
// is a change of delivery phase or revision for one (project, environment) —
// which is what a deployment landing looks like from the outside, so there is
// no separate "deployment" event type. A HEALTH_CHANGE is a change of the
// observation plane's verdict for one workload. Policy decisions are the third
// item of #76's taxonomy and are not here: no policy engine exists yet (#75).
// When it does, it adds an event type and a payload to this file; nothing
// already on the wire changes meaning.

