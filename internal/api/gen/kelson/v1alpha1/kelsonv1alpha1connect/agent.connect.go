// AgentService: agent identities as first-class principals (issue #74,
// ADR-0024).
//
// An agent is a principal, not a human with a borrowed token. The shared
// password of #84's interim cut says a caller may reach the server; it never
// says who the caller is, so an action cannot be attributed, a permission
// cannot be narrower than the human's, and revoking an agent means changing the
// password on every human at once. This service issues credentials that answer
// all three: a named identity, a scope narrower than the operator's, and a
// revocation that touches nothing else.
//
// # The token is returned exactly once
//
// CreateAgentResponse.token is the only place a credential value appears in
// this schema. The server stores a salted HMAC of it and nothing else, so
// ListAgents cannot re-reveal it and neither can the server — a lost token is
// re-issued (create a new identity, revoke the old one), never recovered. That
// is the same rule ADR-0009 applies to secret values, for the same reason: a
// surface that can read a credential back is a surface that leaks it.
//
// # Only a human may mint an identity
//
// Every RPC here is administrative and is refused to an agent credential
// server-side, whatever its scope (ADR-0024). An agent that could mint an agent
// could mint one wider than itself, which would make every scope advisory. The
// same three operations are available to an operator with a kube context as
// `kelson agent create|list|revoke`, authorized by the cluster's own RBAC.
//
// # Scope is (project, environment, operation)
//
// An empty project or environment list means "every one" — a deliberately
// unscoped credential — and an empty list is therefore never the default the
// CLI hands out. Operations are classes, not method names: READ covers status,
// logs, render and diff; MUTATE covers deploy, promote, rollback, build, spec
// writes and secret writes, and implies READ. The method-to-class mapping is
// one table in internal/api with a coverage test over the registered schema, so
// an RPC added without a class fails closed rather than defaulting to allowed.

