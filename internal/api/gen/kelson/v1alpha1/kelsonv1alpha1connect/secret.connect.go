// SecretService: the authoring half of ADR-0009's `cluster` secret backend
// (issue #116), served.
//
// A kelson spec carries secret references, never values. `{secret: <name>,
// key: <key>}` renders as a valueFrom.secretKeyRef against a Secret in the
// environment's namespace (ADR-0018); this service is what writes that Secret.
//
// # Values travel in, never out
//
// SetSecret carries values over the wire. Nothing carries one back:
// ListSecrets and SetSecret's own response return names, keys, namespaces and
// ages, and no message in this file has a field a value could arrive in. That
// is ADR-0009's masked read-back stated as a schema property rather than as a
// handler's promise — a client that wanted the value could not decode one, and
// a future handler that tried to send one would have nowhere to put it.
//
// The server registers every value it receives with internal/redact before it
// does anything else with it, so a value cannot reach a log, an error message
// or an error detail whichever plane writes it (issue #117).
//
// # The backend decides whether these RPCs may write at all
//
// A request here names a project and an environment and carries no spec, but
// the environment's `secrets.backend` is not the caller's to state: the server
// reads it from the stored spec (issue #269). Under `cluster` these RPCs write
// the Secret. Under `sops` and `externalSecrets` the value belongs somewhere
// kelson would not be writing it, so the mutations are refused by name — a
// structured error carrying the backend and where the value does belong —
// rather than writing a cluster Secret the delivery spine would fight.
//
// # Deliberately omitted, and why
//
// **No GetSecret.** Issue #116 leaves the door open to a full-value read that
// is "explicitly requested and audited"; there is no audit log to record it in
// (ADR-0013 §1: the server holds no state), so a read that claimed to be
// audited would be a claim rather than a fact. Reading a value back is
// `kubectl get secret` and the cluster's own RBAC and audit trail.
//
// **No idempotency_key**, which every other mutating RPC in this schema carries
// (issue #69). A key exists so a retry after a timeout is the same operation
// rather than a second one, and every mutation here is already convergent: a
// SetSecret is a server-side apply, so replaying it produces the identical
// object; a DeleteSecret replayed after it succeeded finds nothing and says so;
// and an UnsetSecret replayed after it succeeded finds the key gone, which is a
// refusal rather than a second removal. There is also nowhere to record a key —
// the spec store's idempotency lives in the ConfigMap it writes, and this
// service writes a Secret whose contents are not kelson's to annotate. A field
// that changed no outcome would be worse than its absence.
//
// # UnsetSecret is the complement of the merge, and only that
//
// `SetSecret` merges rather than replaces, so no request in this file can drop
// a key by omission — which left "remove one key" inexpressible until
// UnsetSecret (issue #269). It removes the keys it names and nothing else: a
// key it does not name is refused rather than pruned, and a Secret whose last
// key it removes is left **empty rather than deleted**, so removing keys can
// never remove an object. Taking a Secret away stays DeleteSecret's, which is
// the RPC with the ownership check and the CLI confirmation in front of it.

