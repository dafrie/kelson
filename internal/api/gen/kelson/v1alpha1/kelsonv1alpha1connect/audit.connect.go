// AuditService: what each principal actually did (issue #78, ADR-0026).
//
// # One trail, principal-typed
//
// This is the general audit log of issue #12 and the agent audit trail of #78
// in one implementation. Every record names its principal and that principal's
// type, so "what did the agents do" is a filter on one trail rather than a
// second trail nobody would keep in sync. Distinguishing agent from human is
// therefore a property of the data, not of the storage.
//
// # What is recorded, and what is not
//
// Mutations and refusals. Every mutating call leaves a record — allowed,
// refused or failed — and every *refused* call of any class leaves one, because
// a refusal is a security event and there are few of them. Allowed reads are
// not recorded: a status poll changes nothing, and the volume would evict the
// mutations the trail exists for from a bounded store (ADR-0026 §3). An
// operator who needs read auditing points the server at an external sink; that
// is the recorded way out, and it is not this schema's business.
//
// # The record points at the diff rather than carrying it
//
// `change.revision` names the entry in the environment's rendered history, from
// which the exact manifests and any comparison against them can be
// reconstructed with DeployService.History and the rollback preview. Beside it
// is a bounded summary — counts, kinds touched, max risk — for a reader who
// only wants the blast radius. Manifests are stored once, under a name, and a
// second unbounded copy per record would exhaust the store in one deploy.
//
// # Reading the trail is administrative
//
// QueryAudit is filed under the admin operation class in kelson's RPC scope table,
// beside AgentService. An agent credential cannot read it, whatever its scope:
// the trail is what an operator uses to review what the agents did, and a
// principal that can read its own audit trail can plan around it (ADR-0026 §5).
//
// # Export is this RPC, paged
//
// There is no separate export RPC. `kelson audit --export jsonl` pages QueryAudit to
// exhaustion and writes one JSON object per line, so the filters, the bounds
// and the truncation reporting have exactly one implementation.

