// ExplainService: "why is this application degraded?" answered with
// structured, causal data (issue #77, ADR-0023).
//
// It is the API capability, and `diagnose_application` in the MCP surface
// (issue #73) is its task-shaped presentation. The structured-cause machinery
// lives behind this service — in internal/explain — so the CLI, the UI and the
// agent surface compose one answer instead of implementing three diagnoses.
//
// # A service of its own, not a method on DeployService
//
// ADR-0013 §2 organises services by capability rather than by resource.
// Delivery *control* — deploy, status, rollback, history, promote — and causal
// *analysis* are different capabilities with different readers, and
// DeployService is already the largest service in this schema. A separate
// service also leaves room for the subjects explanation will grow (a build, a
// rejected policy, a preview) without each one widening the deploy contract.
//
// # Read-only, and there is nothing here that could write
//
// Explain renders the spec, asks the adapter for its status, asks the
// observation plane for its verdicts, reads the recorded manifests of two
// revisions and takes a bounded log window. Every one of those is a read.
//
// # Bounded, and the bounds are part of the contract
//
// The response is written to be pasted into a context window whole. The caps
// are enforced server-side by internal/explain and stated on the fields below:
// at most 6 causes, 4 evidence items per cause, 8 log lines per excerpt at 200
// bytes each, and 12 KiB across the whole message. Every cut that fired is
// listed in `truncated` — a truncated answer read as a complete one draws a
// wrong conclusion from a correct report, so nothing is dropped silently.

