// PreviewService: which pull requests of an environment are running
// (ADR-0017 stage 3).
//
// ADR-0017 decision 7 said plainly that kelson's Status and History RPCs do not
// enumerate preview children, and that an API which does "is a new decision
// about what a preview *is* to kelson's model". This service is that decision,
// and it is the smaller of the two it could have been: a preview stays a thing
// the cluster describes, not a second class of Environment. Nothing here writes.
//
// # Read-only, and why there is no Publish
//
// Previews are created by a CI job running `kelson preview publish`
// (ADR-0017 decision 8) and destroyed by flux-operator when the change request
// closes. Neither end of that lifecycle is the server's, so a write RPC here
// would either duplicate the publisher — without the checkout and the image
// reference CI already has — or delete an object flux-operator would recreate on
// its next poll. `Publish` is deferred by ADR-0017, not forgotten.
//
// # The answer is assembled from two sources and says which is which
//
// `settings` is what the spec declares, resolved: it exists whenever the
// Environment carries a `previews:` block, with or without a cluster.
// `lifecycle` and `previews` are what the cluster holds. An environment that
// declares previews and whose delivery mode is not `flux` gets `settings`, no
// cluster read, and the renderer's own `render/previews-require-flux` in
// `errors` — the same structured refusal `kelson render` prints, because hiding
// a gate the spec has already failed would make the UI the only place kelson
// says previews work.

